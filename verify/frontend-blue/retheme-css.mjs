let css = fs.readFileSync(CSS_PATH, 'utf8');
const counts = { hex: 0, rgb: 0 };

// hex 替换（长 key 优先，避免前缀误匹配）
const hexKeys = Object.keys(HEX_MAP).sort((a, b) => b.length - a.length);
for (const key of hexKeys) {
  const re = new RegExp(key.replace('#', '#') + '(?![0-9a-fA-F])', 'gi');
  css = css.replace(re, () => {
    counts.hex += 1;
    return HEX_MAP[key];
  });
}

// rgba() 三元组替换
css = css.replace(/rgba\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,/g, (whole, r, g, b) => {
  const key = `${r},${g},${b}`;
  if (RGB_MAP[key]) {
    counts.rgb += 1;
    return `rgba(${RGB_MAP[key]},`;
  }
  return whole;
});

fs.writeFileSync(CSS_PATH, css, 'utf8');

